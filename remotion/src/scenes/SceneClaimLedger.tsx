import { AbsoluteFill, useCurrentFrame, useVideoConfig, interpolate, spring } from "remotion";

const STATUS_COLORS: Record<string, string> = {
  SUPPORTED: "#10B981",
  UNSUPPORTED: "#EF4444",
  CONTRADICTED: "#EF4444",
  STALE: "#F59E0B",
};

const Row: React.FC<{ claim: string; status: string; evidence: string; delay: number }> = ({
  claim,
  status,
  evidence,
  delay,
}) => {
  const frame = useCurrentFrame();
  const { fps } = useVideoConfig();
  const op = interpolate(frame - delay, [0, 14], [0, 1], { extrapolateLeft: "clamp", extrapolateRight: "clamp" });
  const x = spring({ frame: frame - delay, fps, config: { damping: 22, stiffness: 120 } });
  const statusOp = interpolate(frame - delay - 18, [0, 12], [0, 1], { extrapolateLeft: "clamp", extrapolateRight: "clamp" });
  const color = STATUS_COLORS[status] ?? "#A1A1AA";
  return (
    <div
      style={{
        opacity: op,
        transform: `translateX(${interpolate(x, [0, 1], [-30, 0])}px)`,
        display: "grid",
        gridTemplateColumns: "1fr 180px 1.1fr",
        gap: 18,
        alignItems: "center",
        background: "#15171C",
        border: "1px solid #2A2D35",
        padding: "16px 22px",
        marginBottom: 10,
      }}
    >
      <div style={{ fontFamily: "Inter", fontSize: 17, color: "#F5F5F0", fontWeight: 500 }}>{claim}</div>
      <div
        style={{
          opacity: statusOp,
          fontFamily: "JetBrains Mono",
          fontSize: 12,
          color,
          letterSpacing: 2,
          border: `1px solid ${color}`,
          padding: "5px 10px",
          textAlign: "center",
          textTransform: "uppercase",
        }}
      >
        {status}
      </div>
      <div style={{ fontFamily: "JetBrains Mono", fontSize: 12, color: "#71717A", lineHeight: 1.5 }}>
        {evidence}
      </div>
    </div>
  );
};

